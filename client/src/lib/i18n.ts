export type StringKey = keyof typeof STRINGS;

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  let text: string = STRINGS[key][lang];
  for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export function hasKey(key: string): key is StringKey {
  return key in STRINGS;
}

export function activityLabel(lang: Lang, toolName: string): string {
  const key = `act_${toolName}`;
  return hasKey(key) ? translate(lang, key) : `${translate(lang, 'act_unknown')}: ${toolName}`;
}
